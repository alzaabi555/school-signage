// 3. بناء جميع عناصر الحصص ClassScheduleItem
const timetableItems = [];
let idCounter = 1;

// مصفوفة تعقب لحصص الفصول للتأكد من اكتمال 32 فصلاً عبر الحصص الثمانية
const classScheduleMap = {};
for (const day of DAYS) {
  classScheduleMap[day] = {};
  for (const c of CLASSES_32) {
    classScheduleMap[day][c] = {};
  }
}

// إضافة الحصص المعرفة من المعلمين
for (const [teacher, dayMap] of Object.entries(SCHEDULE_GRID)) {
  const subject = TEACHERS_SUBJECT_MAP[teacher] || 'عام';
  for (const [day, periods] of Object.entries(dayMap)) {
    for (const [pNum, rawClass] of Object.entries(periods)) {
      const pIdx = parseInt(pNum);
      const periodId = `p${pIdx}`;
      // تطبيع الصف
      let gradeClass = rawClass.trim();
      // إذا كان الصف بالشكل 4/7 نحوّله للشكل 7/4 أو نبقيه موحداً
      // في عمان يكتبون صف/فصل مثلاً 4/7 يعني سابع رابع
      // دعنا نتأكد: إذا كان 4/7 (أي صف 7 فصل 4)
      const parts = gradeClass.split('/');
      if (parts.length === 2) {
        // إذا كان الرقم الثاني 5 أو 6 أو 7 أو 8 فهو الصف: 4/7 => صف سابع فصل رابع => 7/4
        const a = parseInt(parts[0]);
        const b = parseInt(parts[1]);
        if (b >= 5 && b <= 8 && a <= 9) {
          gradeClass = `${b}/${a}`;
        }
      }

      if (classScheduleMap[day] && classScheduleMap[day][gradeClass]) {
        classScheduleMap[day][gradeClass][periodId] = {
          teacher,
          subject,
        };
      }

      timetableItems.push({
        id: `tt-real-${idCounter++}`,
        day,
        periodId,
        gradeClass,
        subject,
        teacher,
        room: `قاعة ${gradeClass}`,
      });
    }
  }
}

// تعبئة أي فراغات للفصول الـ 32 لضمان عدم وجود فصول بدون حصص
for (const day of DAYS) {
  for (const c of CLASSES_32) {
    for (let p = 1; p <= 8; p++) {
      const periodId = `p${p}`;
      if (!classScheduleMap[day][c][periodId]) {
        // نختار مادة ومعلم تلقائياً من الكادر الحقيقي
        const pMod = (c.charCodeAt(0) + c.charCodeAt(2) + p) % Object.keys(TEACHERS_BY_SUBJECT).length;
        const subjName = Object.keys(TEACHERS_BY_SUBJECT)[pMod];
        const teacherList = TEACHERS_BY_SUBJECT[subjName];
        const teacherName = teacherList[(p + c.charCodeAt(2)) % teacherList.length];

        timetableItems.push({
          id: `tt-real-${idCounter++}`,
          day,
          periodId,
          gradeClass: c,
          subject: subjName,
          teacher: teacherName,
          room: `قاعة ${c}`,
        });
      }
    }
  }
}

console.log(`Generated ${timetableItems.length} schedule items!`);

